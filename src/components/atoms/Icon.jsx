/**
 * Renders a lucide icon by registry name. Falls back to a neutral dot if a
 * name is missing, rather than throwing — bad content shouldn't crash a page.
 */
export function Icon({ name, size = 20, strokeWidth = 1.75, className = '', ...rest }) {
  const Cmp = registry[name]
  if (!Cmp) {
    if (import.meta.env.DEV) {
      // eslint-disable-next-line no-console
      console.warn(`[Icon] Unknown icon name: "${name}"`)
    }
    return <span className={`inline-block h-1 w-1 rounded-full bg-current ${className}`} aria-hidden="true" />
  }
  return <Cmp size={size} strokeWidth={strokeWidth} className={className} aria-hidden="true" {...rest} />
}
