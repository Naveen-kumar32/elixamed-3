/** Per-category roll-up (count, forms, brands, offer-price range) — computed, never hand-written. */
export function categorySummary(slug) {
  const list = products.filter((p) => p.category === slug)
  const offers = list.map((p) => p.offerPrice)
  return {
    count: list.length,
    forms: [...new Set(list.map((p) => p.form))],
    brands: [...new Set(list.map((p) => p.brand))],
    minOffer: Math.min(...offers),
    maxOffer: Math.max(...offers),
    image: list.find((p) => p.image)?.image ?? null,
  }
}

